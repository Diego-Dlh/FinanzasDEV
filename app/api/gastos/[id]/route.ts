import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { authenticateToken } from '@/lib/auth';
import { expenseSchema } from '@/lib/validators';
import { HttpError, errorResponse, readJson } from '@/lib/http';
import { validateCategory } from '@/lib/categories';
import { findLinkedExpenseIds } from '@/lib/expenseLinks';

interface Params { params: Promise<{ id: string }> }

export async function PUT(request: Request, { params }: Params) {
  const authHeader = request.headers.get('authorization');
  const userId = authenticateToken(authHeader);
  if (!userId) return NextResponse.json({ error: 'No autorizado' }, { status: 401 });

  const { id } = await params;
  const existing = await prisma.expense.findFirst({ where: { id, userId } });
  if (!existing) return NextResponse.json({ error: 'No encontrado' }, { status: 404 });

  try {
    // Expenses generated by a debt/card payment are tied to it (debt, card and account
    // balances). Editing one alone would leave them out of sync.
    if ((await findLinkedExpenseIds([id])).has(id)) {
      throw new HttpError(
        409,
        'Este gasto fue generado por un pago de deuda o abono de tarjeta y no se puede editar. Elimina el gasto (o el pago) para revertirlo y regístralo de nuevo.',
      );
    }

    const parse = expenseSchema.partial().safeParse(await readJson(request));
    if (!parse.success) {
      return NextResponse.json({ error: parse.error.issues[0]?.message ?? 'Datos inválidos' }, { status: 400 });
    }

    const newAmount    = parse.data.amount    ?? existing.amount;
    const newAccountId = parse.data.accountId ?? existing.accountId;
    const accountChanged = newAccountId !== existing.accountId;
    const amountChanged  = newAmount !== existing.amount;

    if (accountChanged) {
      const account = await prisma.account.findFirst({ where: { id: newAccountId, userId } });
      if (!account) return NextResponse.json({ error: 'Cuenta no encontrada' }, { status: 404 });
    }
    if (parse.data.categoryId && parse.data.categoryId !== existing.categoryId) {
      await validateCategory(parse.data.categoryId, 'EXPENSE');
    }

    const expenseUpdate = prisma.expense.update({
      where: { id },
      data: {
        description: parse.data.description ?? existing.description,
        amount:      newAmount,
        categoryId:  parse.data.categoryId  ?? existing.categoryId,
        accountId:   newAccountId,
        date:        parse.data.date        ? new Date(parse.data.date) : existing.date,
        frequency:   parse.data.frequency   ?? existing.frequency,
      },
    });

    if (accountChanged) {
      const ops = [
        expenseUpdate,
        prisma.account.update({ where: { id: existing.accountId }, data: { balance: { increment: existing.amount } } }),
        prisma.account.update({ where: { id: newAccountId },       data: { balance: { decrement: newAmount } } }),
      ] as const;
      const [expense] = await prisma.$transaction([...ops]);
      return NextResponse.json({ expense });
    }

    if (amountChanged) {
      const diff = newAmount - existing.amount;
      const ops = [
        expenseUpdate,
        prisma.account.update({ where: { id: existing.accountId }, data: { balance: { decrement: diff } } }),
      ] as const;
      const [expense] = await prisma.$transaction([...ops]);
      return NextResponse.json({ expense });
    }

    const expense = await expenseUpdate;
    return NextResponse.json({ expense });
  } catch (error) {
    return errorResponse(error);
  }
}

export async function DELETE(request: Request, { params }: Params) {
  const authHeader = request.headers.get('authorization');
  const userId = authenticateToken(authHeader);
  if (!userId) return NextResponse.json({ error: 'No autorizado' }, { status: 401 });

  const { id } = await params;
  const existing = await prisma.expense.findFirst({ where: { id, userId } });
  if (!existing) return NextResponse.json({ error: 'No encontrado' }, { status: 404 });

  try {
    await prisma.$transaction(async (tx) => {
      // Deleting first makes every reversal below happen exactly once, even on a double click
      const deleted = await tx.expense.deleteMany({ where: { id, userId } });
      if (deleted.count !== 1) throw new HttpError(404, 'No encontrado');

      // Expense created by a debt payment: also restore the debt
      const linkedPayment = await tx.payment.findFirst({ where: { expenseId: id, userId } });
      if (linkedPayment) {
        await tx.debt.updateMany({
          where: { id: linkedPayment.debtId, userId },
          data: { balance: { increment: linkedPayment.amount } },
        });
        await tx.payment.deleteMany({ where: { id: linkedPayment.id, userId } });
      }

      // Expense created by a card payment: also restore the card balance (in full, no clamping)
      const linkedCardPayment = await tx.cardPayment.findFirst({ where: { expenseId: id, userId } });
      if (linkedCardPayment) {
        await tx.creditCard.updateMany({
          where: { id: linkedCardPayment.cardId, userId },
          data: { usedBalance: { increment: linkedCardPayment.amount } },
        });
        await tx.cardPayment.deleteMany({ where: { id: linkedCardPayment.id, userId } });
      }

      await tx.account.update({ where: { id: existing.accountId }, data: { balance: { increment: existing.amount } } });
    });
  } catch (error) {
    return errorResponse(error);
  }

  return NextResponse.json({ ok: true });
}
