import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { authenticateToken } from '@/lib/auth';
import { expenseSchema } from '@/lib/validators';
import { api, HttpError, parseBody } from '@/lib/http';
import { validateCategory } from '@/lib/categories';
import { findLinkedExpenseIds } from '@/lib/expenseLinks';
import { lockExpense } from '@/lib/rowLocks';

interface Params { params: Promise<{ id: string }> }

async function handlePut(request: Request, { params }: Params) {
  const authHeader = request.headers.get('authorization');
  const userId = await authenticateToken(authHeader);
  if (!userId) return NextResponse.json({ error: 'No autorizado' }, { status: 401 });

  const { id } = await params;
  const existing = await prisma.expense.findFirst({ where: { id, userId } });
  if (!existing) return NextResponse.json({ error: 'No encontrado' }, { status: 404 });

  // Expenses generated by a debt/card payment are tied to it (debt, card and account
  // balances). Editing one alone would leave them out of sync.
  if ((await findLinkedExpenseIds([id])).has(id)) {
    throw new HttpError(
      409,
      'Este gasto fue generado por un pago de deuda o abono de tarjeta y no se puede editar. Elimina el gasto (o el pago) para revertirlo y regístralo de nuevo.',
    );
  }

  const data = await parseBody(request, expenseSchema.partial());
  if (data.categoryId && data.categoryId !== existing.categoryId) {
    await validateCategory(data.categoryId, 'EXPENSE');
  }

  const expense = await prisma.$transaction(async (tx) => {
    // Lock, then re-read: the balance difference must be computed from the current row
    await lockExpense(tx, id);
    const current = await tx.expense.findFirst({ where: { id, userId } });
    if (!current) throw new HttpError(404, 'No encontrado');

    const newAmount    = data.amount    ?? current.amount;
    const newAccountId = data.accountId ?? current.accountId;
    const accountChanged = newAccountId !== current.accountId;

    if (accountChanged) {
      const account = await tx.account.findFirst({ where: { id: newAccountId, userId } });
      if (!account) throw new HttpError(404, 'Cuenta no encontrada');
    }

    const updated = await tx.expense.update({
      where: { id },
      data: {
        description: data.description ?? current.description,
        amount:      newAmount,
        categoryId:  data.categoryId  ?? current.categoryId,
        accountId:   newAccountId,
        date:        data.date        ? new Date(data.date) : current.date,
        frequency:   data.frequency   ?? current.frequency,
      },
    });

    if (accountChanged) {
      await tx.account.update({ where: { id: current.accountId }, data: { balance: { increment: current.amount } } });
      await tx.account.update({ where: { id: newAccountId },      data: { balance: { decrement: newAmount } } });
    } else if (newAmount !== current.amount) {
      await tx.account.update({ where: { id: current.accountId }, data: { balance: { decrement: newAmount - current.amount } } });
    }
    return updated;
  });

  return NextResponse.json({ expense });
}

async function handleDelete(request: Request, { params }: Params) {
  const authHeader = request.headers.get('authorization');
  const userId = await authenticateToken(authHeader);
  if (!userId) return NextResponse.json({ error: 'No autorizado' }, { status: 401 });

  const { id } = await params;

  await prisma.$transaction(async (tx) => {
    // Lock, then re-read: concurrent deletes must reverse everything exactly once
    await lockExpense(tx, id);
    const current = await tx.expense.findFirst({ where: { id, userId } });
    if (!current) throw new HttpError(404, 'No encontrado');

    await tx.expense.delete({ where: { id } });

    // Expense created by a debt payment: also restore the debt
    const linkedPayment = await tx.payment.findFirst({ where: { expenseId: id, userId } });
    if (linkedPayment) {
      await tx.debt.updateMany({
        where: { id: linkedPayment.debtId, userId },
        data: { balance: { increment: linkedPayment.amount } },
      });
      await tx.payment.deleteMany({ where: { id: linkedPayment.id, userId } });
    }

    // Expense created by a card payment: also restore the card balance (in full, no clamping)
    const linkedCardPayment = await tx.cardPayment.findFirst({ where: { expenseId: id, userId } });
    if (linkedCardPayment) {
      await tx.creditCard.updateMany({
        where: { id: linkedCardPayment.cardId, userId },
        data: { usedBalance: { increment: linkedCardPayment.amount } },
      });
      await tx.cardPayment.deleteMany({ where: { id: linkedCardPayment.id, userId } });
    }

    await tx.account.update({ where: { id: current.accountId }, data: { balance: { increment: current.amount } } });
  });

  return NextResponse.json({ ok: true });
}

export const PUT = api(handlePut);
export const DELETE = api(handleDelete);
